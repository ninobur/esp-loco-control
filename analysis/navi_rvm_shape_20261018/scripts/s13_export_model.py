"""Writes firmware/test-programs/NAVI_RVM_SHAPE_MANUAL/RvmShapeModel.h from
results/local/model_A.json. Per Gaussian component: mean, inverse Cholesky factor
(lower triangle) and log(w) - log|L| - d/2 log(2 pi). Generated; do not edit."""
import numpy as np, json, hashlib
from common import *
import rvm_shape as R
src = ROOT/'results'/'local'/'model_A.json'
m = json.load(open(src)); sha = hashlib.sha256(open(src, 'rb').read()).hexdigest()
out = ROOT.parents[1]/'firmware'/'test-programs'/'NAVI_RVM_SHAPE_MANUAL'/'RvmShapeModel.h'
d = R.NDCT + 1
def comps(cls):
    rows = []
    for w, mu, S in zip(cls['w'], cls['mu'], cls['S']):
        L = np.linalg.cholesky(np.array(S)); Li = np.linalg.inv(L)
        k = np.log(w) - np.log(np.diag(L)).sum() - 0.5 * d * np.log(2 * np.pi)
        tri = [Li[i, j] for i in range(d) for j in range(i + 1)]
        rows.append((k, mu, tri))
    return rows
f = lambda v: ', '.join('%.9ef' % x for x in v)
with open(out, 'w') as o:
    o.write('#pragma once\n// GENERATED by analysis/navi_rvm_shape_20261018/scripts/s13_export_model.py - do not edit.\n')
    o.write(f'// Source: results/local/model_A.json sha256 {sha}\n// {m["note"]}\n')
    o.write('// Model A (general composite), local-baseline features: 12 DCT shape coefficients + log(A/noise).\n')
    o.write('#include <stdint.h>\nnamespace rvm_shape {\n')
    o.write(f'static constexpr int NPT = {R.NPT}, NDCT = {R.NDCT}, DIM = {d}, MIN_BL = 2;\n')
    o.write(f'static constexpr int N_SCALES = {len(R.SCALES)};\nstatic const uint16_t SCALES[N_SCALES] = {{{", ".join(map(str, R.SCALES))}}};\n')
    o.write(f'static constexpr int MAX_W = {int(R.SCALES[-1])};\n')
    o.write(f'static const float DCT[NDCT][NPT] = {{\n' + ',\n'.join('  {' + f(r) + '}' for r in R.DCT) + '\n};\n')
    o.write('struct Component { float k; float mu[DIM]; float linv[DIM * (DIM + 1) / 2]; };\n')
    for name, key in (('E', 'E'), ('N', 'N')):
        cs = comps(m[key])
        o.write(f'static constexpr int N_{name} = {len(cs)};\nstatic const Component COMP_{name}[N_{name}] = {{\n')
        o.write(',\n'.join('  {%.9ef, {%s}, {%s}}' % (k, f(mu), f(tri)) for k, mu, tri in cs) + '\n};\n')
    o.write(f'static const char MODEL_SHA256[] = "{sha[:16]}";\n}}  // namespace rvm_shape\n')
print(out, 'written')
